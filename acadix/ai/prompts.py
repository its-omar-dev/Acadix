"""Prompt templates used by Acadix."""
from textwrap import dedent


def roadmap_prompt(topic, level):
    return dedent(
        f"""
        أنت مستشار أكاديمي وخبير تعليمي رفيع المستوى. بصفتك موجهًا ومستشارًا في مجال '{topic}', قم بإعداد "خارطة طريق شمولية واحترافية" باللغة العربية مخصصة لشخص مستواه حالياً: [{level}].

        التزم بهذه البنية بالضبط (Markdown):

        ## الملخص التنفيذي
        - ثلاث نقاط موجزة عن أهمية '{topic}' لمستوى ({level}).

        ## المرحلة 1: عنوان قصير
        جملة واحدة تصف المرحلة.
        - [ ] مهمة قصيرة وواضحة
        - [ ] مهمة قصيرة وواضحة

        كرر نفس الشكل للمراحل 2 إلى 4 (تأسيس، توسع، احتراف، سوق العمل)، من 3 إلى 5 مهام لكل مرحلة، ولا تضف أي نص خارج هذه البنية.
        """
    ).strip()
